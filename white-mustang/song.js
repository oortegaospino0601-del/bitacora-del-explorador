// THE SOUNDTRACK — voice only (ElevenLabs take, voice "Nicole – Español Neutro – Narrativa").
// The music bed is added later by the editor, so this file only re-times the narration:
// it cuts the take at its natural pauses, opens a little breathing room between scenes,
// and writes:
//   out/music.wav  48 kHz stereo, loudness-normalised voice track (what `render.js mux` uses)
//   vo-data.js     segments + every word re-timed + a per-frame loudness envelope (read by score.js)
//   node song.js
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const SRC = path.join(__dirname, 'assets/vo/take1.mp3');
const WORDS = JSON.parse(fs.readFileSync(path.join(__dirname, 'assets/vo/words.json'), 'utf8')).words;
const OUT = path.join(__dirname, 'out');
fs.mkdirSync(OUT, { recursive: true });

// [scene, cut-in, cut-out] in the original take (cuts sit inside its natural silences), and
// `pre` = seconds of silence opened before each segment (the scene changes inside that gap).
const SEGS = [
  { id: 'hook', a: 0.0, b: 4.0, pre: 0.6 },
  { id: 'motel', a: 4.0, b: 17.02, pre: 1.0 },
  { id: 'drive', a: 17.02, b: 28.3, pre: 1.1 },
  { id: 'light', a: 28.3, b: 41.88, pre: 1.2 },
  { id: 'road', a: 41.88, b: 54.84, pre: 1.6 },
  { id: 'close', a: 54.84, b: 59.62, pre: 2.6 },
];
const TAIL = 4.2;

let cur = 0;
for (const s of SEGS) { cur += s.pre; s.t = +cur.toFixed(3); cur += s.b - s.a; s.end = +cur.toFixed(3); }
const DURATION = +(cur + TAIL).toFixed(3);

// re-time every word into the new timeline
const words = WORDS.filter((w) => w.type === 'word').map((w) => {
  const s = SEGS.find((g) => w.start >= g.a - 1e-6 && w.start < g.b) || SEGS[SEGS.length - 1];
  const sh = s.t - s.a;
  return { w: w.text, t: +(w.start + sh).toFixed(3), end: +(w.end + sh).toFixed(3), seg: s.id };
});

// ffmpeg: slice, short fades at the cuts, place, mix, loudness-normalise
const parts = SEGS.map((s, i) => {
  const d = s.b - s.a;
  return `[0:a]atrim=${s.a}:${s.b},asetpts=PTS-STARTPTS,afade=t=in:st=0:d=0.012,afade=t=out:st=${(d - 0.03).toFixed(3)}:d=0.03,adelay=${Math.round(s.t * 1000)}:all=1[p${i}]`;
});
const fc = parts.join(';') + ';' + SEGS.map((_, i) => `[p${i}]`).join('') +
  `amix=inputs=${SEGS.length}:normalize=0:duration=longest,highpass=f=70,loudnorm=I=-15:TP=-1.5:LRA=9,aresample=48000,` +
  `apad=whole_dur=${DURATION},atrim=0:${DURATION}[out]`; // pad AFTER loudnorm (it drops trailing silence)
const wav = path.join(OUT, 'music.wav');
execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', SRC, '-filter_complex', fc, '-map', '[out]', '-ac', '2', '-ar', '48000', '-c:a', 'pcm_s16le', wav]);

// loudness envelope at the film's 30 fps (drives the sound waves on screen)
const raw = execFileSync('ffmpeg', ['-v', 'error', '-i', wav, '-ac', '1', '-ar', '48000', '-f', 'f32le', '-'], { maxBuffer: 1 << 30 });
const pcm = new Float32Array(raw.buffer, raw.byteOffset, raw.length / 4);
const hop = 48000 / 30, env = [];
for (let i = 0; i * hop < pcm.length; i++) {
  let acc = 0; const a = Math.floor(i * hop), b = Math.min(pcm.length, Math.floor((i + 1) * hop));
  for (let j = a; j < b; j++) acc += pcm[j] * pcm[j];
  env.push(Math.sqrt(acc / Math.max(1, b - a)));
}
const peak = Math.max(...env) || 1;
const envQ = env.map((v) => Math.round((v / peak) * 100));

const VO = { DURATION, segs: SEGS.map(({ id, t, end, pre }) => ({ id, t, end, pre })), words, env: envQ, envFps: 30 };
fs.writeFileSync(path.join(__dirname, 'vo-data.js'),
  '// generated by song.js: the narration re-timed (segments, words, loudness envelope). Do not edit.\n' +
  '(function(){const VO=' + JSON.stringify(VO) + ';if(typeof module!=="undefined")module.exports=VO;else globalThis.VO=VO;})();\n');
console.log(`wrote out/music.wav + vo-data.js (${DURATION.toFixed(2)}s)`);
for (const s of VO.segs) console.log(`  ${s.id.padEnd(6)} ${s.t.toFixed(2)} → ${s.end.toFixed(2)}`);
